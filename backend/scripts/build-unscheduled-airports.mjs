#!/usr/bin/env node
/**
 * Builds backend/src/data/unscheduledAirportCodes.ts — the IATA codes of
 * catalogue airports that OurAirports marks as having NO scheduled service
 * (air bases, business and general-aviation fields that happen to carry an
 * IATA code: GKE Geilenkirchen, MGL Mönchengladbach, SPM Spangdahlem, …).
 *
 * Why a vendored list: the airport table has no type or service column, and
 * the "Zuhause" settings offer nearby airports as home airports. Without this
 * signal the offer for Köln listed a NATO air base above Dortmund. The source
 * CSV carries `scheduled_service`; the table does not, so the signal is
 * derived here, at build time, into a file.
 *
 * It is a DENY list on purpose: a code missing from it (a new airport, a
 * user-added one) is still offered — the failure mode of a stale list is the
 * old behaviour, never a hidden airport.
 *
 * A code is listed only when EVERY active large/medium airport carrying it has
 * `scheduled_service != "yes"` — the catalogue admits exactly those types
 * (shared/antarcticAirfields.ts `admitsAirport`).
 *
 * Usage (network only when the CSV is absent):
 *   node backend/scripts/build-unscheduled-airports.mjs [path/to/airports.csv]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "csv-parse/sync";

const here = path.dirname(fileURLToPath(import.meta.url));
const csvPath = process.argv[2] ?? path.join(here, "..", "airports.csv");
const outPath = path.join(here, "..", "src", "data", "unscheduledAirportCodes.ts");
const SOURCE_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const CODES_PER_LINE = 14;

async function readCsv() {
  if (fs.existsSync(csvPath)) return fs.readFileSync(csvPath, "utf-8");
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`download failed: HTTP ${res.status}`);
  return res.text();
}

const records = parse(await readCsv(), { columns: true, skip_empty_lines: true });
const scheduled = new Set();
const unscheduled = new Set();
for (const r of records) {
  if (r.type !== "large_airport" && r.type !== "medium_airport") continue;
  const code = (r.iata_code || "").trim().toUpperCase();
  if (!/^[A-Z]{3}$/.test(code)) continue;
  (r.scheduled_service === "yes" ? scheduled : unscheduled).add(code);
}
const codes = [...unscheduled].filter((c) => !scheduled.has(c)).sort();
if (codes.length < 500) {
  throw new Error(`only ${codes.length} codes — the CSV looks wrong, refusing to write`);
}

const lines = [];
for (let i = 0; i < codes.length; i += CODES_PER_LINE) {
  lines.push(`  "${codes.slice(i, i + CODES_PER_LINE).join(" ")}",`);
}
const body = `/**
 * GENERATED by backend/scripts/build-unscheduled-airports.mjs — do not edit.
 * Source: OurAirports airports.csv (public domain), ${SOURCE_URL}
 *
 * IATA codes of large/medium airports WITHOUT scheduled passenger service
 * (air bases, business fields). ${codes.length} codes. Read through
 * services/home/nearbyAirports.ts; see the script for why it is a deny list.
 */
const CHUNKS: readonly string[] = [
${lines.join("\n")}
];

export const UNSCHEDULED_AIRPORT_CODES: ReadonlySet<string> = new Set(
  CHUNKS.flatMap((chunk) => chunk.split(" "))
);
`;
fs.writeFileSync(outPath, body);
console.log(`wrote ${codes.length} codes to ${path.relative(process.cwd(), outPath)}`);
