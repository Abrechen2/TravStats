const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const backend=path.resolve(__dirname,'../../.tmp/audit-round2-9678e6cd/backend');
const url=new URL(process.env.DATABASE_URL);
assert.equal(url.hostname,'127.0.0.1');assert.equal(url.port,'55439');assert.equal(url.pathname,'/travstats_block12_probe_audit');assert.equal(process.env.NODE_ENV,'test');
require(path.join(backend,'node_modules/tsx/dist/cjs/index.cjs'));
const {prisma}=require(path.join(backend,'src/db.ts'));
const {mergeTrips}=require(path.join(backend,'src/services/tripCleanupService.ts'));
const {buildLodgingPreviewRows}=require(path.join(backend,'src/services/lodging/lodgingImportPreview.ts'));
const {commitLodgingImport}=require(path.join(backend,'src/services/lodging/lodgingImportCommit.ts'));
const output={commit:'9678e6cd',results:[],previewRows:{}};
async function main(){
  const user=await prisma.user.create({data:{username:'block12-data-'+Date.now(),passwordHash:'synthetic-unused'}});
  const trips=[];
  for(const name of ['Target','Source A','Source B'])trips.push(await prisma.trip.create({data:{userId:user.id,name}}));
  for(let i=1;i<3;i++)await prisma.tripPhoto.create({data:{tripId:trips[i].id,filename:`synthetic-source-${i}.jpg`,mimetype:'image/jpeg',sizeBytes:1,immichAssetId:'synthetic-shared-asset'}});
  await mergeTrips(user.id,{tripIds:trips.map(t=>t.id),targetId:trips[0].id});
  assert.equal(await prisma.trip.count({where:{userId:user.id}}),1);
  assert.equal(await prisma.tripPhoto.count({where:{tripId:trips[0].id}}),1);
  output.results.push({name:'AUD-029 multiple sources with duplicate photo asset',mergeSucceeded:true,survivingPhotos:1});
  const src=await prisma.trip.create({data:{userId:user.id,name:'Cover Source'}});
  const duplicate=await prisma.tripPhoto.create({data:{tripId:src.id,filename:'synthetic-cover.jpg',mimetype:'image/jpeg',sizeBytes:1,immichAssetId:'synthetic-shared-asset'}});
  await prisma.trip.update({where:{id:src.id},data:{coverImageUrl:`/api/v1/trips/${src.id}/photos/${duplicate.id}/file`}});
  await mergeTrips(user.id,{tripIds:[trips[0].id,src.id],targetId:trips[0].id});
  const target=await prisma.trip.findUniqueOrThrow({where:{id:trips[0].id}});
  const surviving=await prisma.tripPhoto.findFirstOrThrow({where:{tripId:target.id}});
  assert.equal(target.coverImageUrl,`/api/v1/trips/${target.id}/photos/${surviving.id}/file`);
  output.results.push({name:'AUD-030 cover follows surviving photo',pointsToExistingRow:true});
  const lodging=await prisma.lodging.create({data:{userId:user.id,name:'Audit Hotel',type:'hotel',city:'Berlin'}});
  const candidate={sourceRowIndex:0,lodging:{name:'Audit Hotel',city:'Berlin'},stay:{checkIn:'2026-04-01',checkOut:'2026-04-03'}};
  const before=await buildLodgingPreviewRows(user.id,[candidate]);
  output.previewRows.heuristicControl=before.rows[0];
  await prisma.lodgingStay.create({data:{userId:user.id,lodgingId:lodging.id,checkIn:new Date('2026-04-01'),checkOut:new Date('2026-04-03'),status:'completed'}});
  const withStay=await buildLodgingPreviewRows(user.id,[candidate]);
  output.previewRows.sameDateHeuristic=withStay.rows[0];
  const join=await buildLodgingPreviewRows(user.id,[{sourceRowIndex:0,lodging:null,lodgingName:'Audit Hotel',stay:{checkIn:'2026-05-01',checkOut:'2026-05-03'}}]);
  output.previewRows.nameJoin=join.rows[0];
  assert.equal(output.previewRows.heuristicControl.dedupeHint,'lodging_name_city');
  assert.equal(output.previewRows.sameDateHeuristic.dedupeHint,'stay_same_dates');
  assert.equal(output.previewRows.nameJoin.dedupeHint,'none');
  const committed=await commitLodgingImport(user.id,'csv','synthetic-audit.csv',[{sourceRowIndex:0,action:'create',matchedLodgingId:lodging.id,lodging:null,lodgingName:'Audit Hotel',stay:{checkIn:'2026-05-01',checkOut:'2026-05-03'}}]);
  assert.equal(committed.createdLodgings,0);assert.equal(committed.createdStays,1);
  output.results.push({name:'name-only guessed join follows original hotel when create selected',createdLodgings:committed.createdLodgings,createdStays:committed.createdStays});
}
main().catch(error=>{output.error=error.message;process.exitCode=1;}).finally(async()=>{await prisma.$disconnect();fs.writeFileSync(path.join(__dirname,'block12-data-probes.json'),JSON.stringify(output,null,2));console.log(JSON.stringify(output));});
