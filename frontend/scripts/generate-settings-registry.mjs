#!/usr/bin/env node
/**
 * Generates `src/pages/Settings/registry/data/<page>.ts` from the designer's
 * `settings-data.json` (round 2, 2026-11-01).
 *
 *   node scripts/generate-settings-registry.mjs          write the files
 *   node scripts/generate-settings-registry.mjs --check  fail when they differ
 *
 * Nothing about a setting is decided here: the data says which rows are expert
 * (`x`), instance-wide (`sc: "i"`), admin-only (`ad`), demo-locked (`d`), tied to
 * a domain (`dom`) or to a beta key. Inheritance is page -> section -> row; a row
 * with `x: 0` is standard inside an expert section.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(
  here,
  "../../ClaudeDesign/handoff/2026-11-01-einstellungen-neu/antwort-runde-2/settings-data.json"
);
const OUT = resolve(here, "../src/pages/Settings/registry/data");
const check = process.argv.includes("--check");

const DOMAIN = { hotel: "lodging", tour: "roadtrip" };
const GROUP = { du: "account", instanz: "server", fuss: "about" };
const level = (x) => (x ? "expert" : "standard");
const q = (v) => JSON.stringify(v);

function rowOf(page, section, r) {
  const expert = r.x === 0 ? false : Boolean(r.x ?? section.x ?? page.x);
  const dom = r.dom ?? page.dom;
  const options = (list) => (Array.isArray(list) ? list.join(" ") : "");
  const row = {
    id: r.id,
    kind: r.t,
    level: level(expert),
    scope: r.sc === "i" || section.sc === "i" || page.sc === "i" ? "instance" : "account",
    audience: r.ad || section.ad || page.ad ? "admin" : "all",
    ...(dom ? { domain: DOMAIN[dom] ?? dom } : {}),
    ...((r.beta ?? section.beta) ? { beta: r.beta ?? section.beta } : {}),
    demoLocked: Boolean(r.d ?? section.d ?? page.d),
    de: r.de[0],
    en: r.en[0],
    terms: {
      de: [r.de[1], r.de[2], options(r.o)].filter(Boolean).join(" "),
      en: [r.en[1], r.en[2], options(r.oe ?? r.o)].filter(Boolean).join(" "),
    },
  };
  return row;
}

function sectionSource(page, s) {
  const svc = s.svc;
  const de = s.de ?? svc?.n?.[0] ?? s.id;
  const en = s.en ?? svc?.n?.[1] ?? s.id;
  const head = {
    id: s.id,
    de,
    en,
    level: level(Boolean(s.x ?? page.x)),
    scope: s.sc === "i" || page.sc === "i" ? "instance" : "account",
    audience: s.ad || page.ad ? "admin" : "all",
    ...(s.beta ? { beta: s.beta } : {}),
    demoLocked: Boolean(s.d ?? page.d),
    ...(s.cat ? { serviceCategory: s.cat } : {}),
  };
  const rows = s.rows.map((r) => `        ${q(rowOf(page, s, r))},`).join("\n");
  const body = JSON.stringify(head).slice(0, -1);
  return `      ${body},"rows":[\n${rows}\n      ]},`;
}

const constName = (id) => `${id.toUpperCase()}_PAGE`;

function pageSource(page) {
  const head = {
    id: page.id,
    group: GROUP[page.g],
    de: page.de,
    en: page.en,
    level: level(Boolean(page.x)),
    audience: page.ad ? "admin" : "all",
    ...(page.dom ? { domain: DOMAIN[page.dom] ?? page.dom } : {}),
    demoLocked: Boolean(page.d),
  };
  const sections = page.s.map((s) => sectionSource(page, s)).join("\n");
  return `// Generated by frontend/scripts/generate-settings-registry.mjs from the designer's
// settings-data.json (round 2). Do not edit: change the data and regenerate.
import type { RegistryPage } from "../types";

export const ${constName(page.id)}: RegistryPage = {
  ...${JSON.stringify(head)},
  sections: [
${sections}
  ],
};
`;
}

const data = JSON.parse(readFileSync(SOURCE, "utf8"));
mkdirSync(OUT, { recursive: true });
let stale = 0;
for (const page of data.pages) {
  const file = join(OUT, `${page.id}.ts`);
  const next = pageSource(page);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== next) {
      console.error(`stale: ${file}`);
      stale += 1;
    }
  } else {
    writeFileSync(file, next);
  }
}
const index = `// Generated: the pages of the settings registry, in the designer's order.
${data.pages.map((p) => `import { ${constName(p.id)} } from "./${p.id}";`).join("\n")}
import type { RegistryPage } from "../types";

export const REGISTRY_PAGES: readonly RegistryPage[] = [
${data.pages.map((p) => `  ${constName(p.id)},`).join("\n")}
];
`;
const indexFile = join(OUT, "index.ts");
if (check) {
  if (!existsSync(indexFile) || readFileSync(indexFile, "utf8") !== index) {
    console.error(`stale: ${indexFile}`);
    stale += 1;
  }
} else writeFileSync(indexFile, index);
if (stale > 0) process.exit(1);
