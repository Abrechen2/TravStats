import type { RailTimes } from "./times";
/** The same four members as a rail ride's times; the OpenAPI name is `FerryTimes`. */
export type FerryTimes = RailTimes;
export type FerryStatus = "scheduled" | "in_progress" | "completed" | "cancelled";
export type FerryDistanceSource = "great_circle" | "user" | "sea_route";
export type FerryGeometrySource = "straight" | "manual" | "sea_route";
export interface FerryJourney {
  id: string;
  roadtripLegId: string | null;
  userId: string;
  operator: string | null;
  vesselName: string | null;
  /** The vessel the live position reads; bound on the first answered lookup. */
  vesselMmsi: string | null;
  vehicleType: string | null;
  vehicleRegistration: string | null;
  vehicleLengthM: number | null;
  vehicleWidthM: number | null;
  vehicleHeightM: number | null;
  passengerCount: number | null;
  cabinType: string | null;
  ticketReference: string | null;
  depStationName: string;
  depAddress: string | null;
  depLat: number;
  depLon: number;
  depCountry: string | null;
  depTimezone: string | null;
  arrStationName: string;
  arrAddress: string | null;
  arrLat: number;
  arrLon: number;
  arrCountry: string | null;
  arrTimezone: string | null;
  departureTime: string;
  arrivalTime: string | null;
  distanceKm: number | null;
  distanceSource: FerryDistanceSource | null;
  geometry: [number, number][] | null;
  geometrySource: FerryGeometrySource;
  actualDepartureTime: string | null;
  actualArrivalTime: string | null;
  fareClass: string | null;
  seat: string | null;
  bookingReference: string | null;
  price: number | null;
  currency: string | null;
  status: FerryStatus;
  delayMinutes: number | null;
  notes: string | null;
  tags: string[];
  companions: string[];
  tripId: string | null;
  bookingId: string | null;
  externalRef?: string | null;
  trip?: { id: string; name: string; color: string } | null;
  times?: FerryTimes;
  createdAt: string;
  updatedAt: string;
}

export type TripFerryJourney = FerryJourney;
